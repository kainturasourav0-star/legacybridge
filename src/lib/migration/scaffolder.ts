import { ServiceScaffold, ServiceCandidate } from '@/types';

export class ServiceScaffoldGenerator {
  /**
   * Generates production-ready, reviewable service scaffold files
   */
  generateScaffold(service: ServiceCandidate): ServiceScaffold {
    const isPython = service.id === 'svc-inventory';
    const lang = isPython ? 'python' : 'typescript';
    const framework = isPython ? 'fastapi' : 'express';

    const files = isPython
      ? this.generateFastAPIFiles(service)
      : this.generateTypeScriptFiles(service);

    const openApiSpec = JSON.stringify(
      {
        openapi: '3.1.0',
        info: {
          title: `${service.name} API`,
          version: '1.0.0',
          description: service.responsibility,
        },
        paths: {
          '/api/v1/health': {
            get: {
              summary: 'Service health check',
              responses: { '200': { description: 'Healthy' } },
            },
          },
          ...service.proposedEndpoints.reduce((acc, ep) => {
            acc[ep.path] = {
              [ep.method.toLowerCase()]: {
                summary: ep.summary,
                responses: { '200': { description: 'Successful response' } },
              },
            };
            return acc;
          }, {} as Record<string, any>),
        },
      },
      null,
      2
    );

    const dockerfile = isPython
      ? `FROM python:3.11-slim
WORKDIR /app
COPY requirements.txt .
RUN pip install --no-cache-dir -r requirements.txt
COPY . .
EXPOSE 8000
CMD ["uvicorn", "main:app", "--host", "0.0.0.0", "--port", "8000"]
`
      : `FROM node:20-alpine
WORKDIR /app
COPY package*.json ./
RUN npm ci --only=production
COPY . .
EXPOSE 3000
CMD ["node", "dist/index.js"]
`;

    return {
      id: `scaffold-${service.id}`,
      serviceId: service.id,
      serviceName: service.name,
      language: lang,
      framework,
      files,
      openApiSpec,
      dockerfile,
      createdAt: new Date().toISOString(),
    };
  }

  private generateTypeScriptFiles(service: ServiceCandidate) {
    return [
      {
        path: 'src/index.ts',
        description: 'Microservice entrypoint and HTTP route bindings',
        hasTodoNotice: false,
        content: `import express, { Request, Response } from 'express';
import helmet from 'helmet';

const app = express();
app.use(helmet());
app.use(express.json());

// Health & readiness probe
app.get('/health', (_req: Request, res: Response) => {
  res.json({ status: 'ok', service: '${service.name}', timestamp: new Date().toISOString() });
});

${service.proposedEndpoints
  .map(
    (ep) => `// ${ep.summary}
app.${ep.method.toLowerCase()}('${ep.path}', async (req: Request, res: Response) => {
  try {
    // TODO: Connect domain orchestrator
    res.json({ success: true, message: 'Endpoint scaffolded by LegacyBridge' });
  } catch (err: any) {
    res.status(500).json({ error: err.message });
  }
});`
  )
  .join('\n\n')}

const PORT = process.env.PORT || 3000;
app.listen(PORT, () => {
  console.log(\`${service.name} listening on port \${PORT}\`);
});
`,
      },
      {
        path: 'src/domain/rules.ts',
        description: 'Extracted business rules with explicit verification TODO markers',
        hasTodoNotice: true,
        content: `/**
 * Extracted Domain Rules for ${service.name}
 * Generated by LegacyBridge Static AST Miner
 */

export interface VolumeDiscountResult {
  discountRate: number;
  discountAmount: number;
  totalAfterDiscount: number;
}

// Extracted from legacy monolith L25-L39
export function calculateVolumeDiscount(quantity: number, unitPrice: number): VolumeDiscountResult {
  let discountRate = 0.0;
  if (quantity >= 100) {
    discountRate = 0.20;
  } else if (quantity >= 50) {
    discountRate = 0.15;
  } else if (quantity >= 20) {
    discountRate = 0.08;
  }
  const subtotal = quantity * unitPrice;
  const discountAmount = subtotal * discountRate;
  return { discountRate, discountAmount, totalAfterDiscount: subtotal - discountAmount };
}

// TODO: HUMAN ARCHITECT REVIEW REQUIRED
// Verify whether maximum credit line caps should be loaded dynamically from the Credit Service via gRPC
// or cached locally with Redis TTL.
`,
      },
    ];
  }

  private generateFastAPIFiles(service: ServiceCandidate) {
    return [
      {
        path: 'main.py',
        description: 'FastAPI application entrypoint with Pydantic validation',
        hasTodoNotice: false,
        content: `from fastapi import FastAPI, HTTPException
from pydantic import BaseModel, Field
from typing import List, Optional
from datetime import datetime

app = FastAPI(title="${service.name}", version="1.0.0")

class HealthResponse(BaseModel):
    status: str
    service: str
    timestamp: datetime

@app.get("/health", response_model=HealthResponse)
async def health():
    return HealthResponse(status="ok", service="${service.name}", timestamp=datetime.utcnow())

class InventoryCheckRequest(BaseModel):
    sku: str = Field(..., description="Stock keeping unit identifier")
    quantity: int = Field(..., gt=0, description="Quantity required")

@app.post("/api/v1/inventory/reserve")
async def reserve_stock(payload: InventoryCheckRequest):
    # TODO: Connect distributed PostgreSQL database pool
    return {"sku": payload.sku, "reserved": True, "hold_expires_seconds": 900}
`,
      },
    ];
  }
}

export const scaffoldGenerator = new ServiceScaffoldGenerator();
